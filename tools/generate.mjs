// Writes area indexes, rubrics and the library table from registry/. --check compares instead of writing.
import fs from 'node:fs';
import path from 'node:path';
import { AREAS, parseArgs, registryPaths, loadRegistry, isDomain } from './registry.mjs';

const opts = parseArgs(process.argv.slice(2));
const { playbooks, units, sections, conflicts } = loadRegistry(opts.root);
const skill = registryPaths(opts.root).skill;

const byId = (a, b) => a.unit_id.localeCompare(b.unit_id);
const owned = (pbId) => units.filter((u) => u.owner === pbId).sort(byId);
const cell = (s) => String(s).replace(/\|/g, '\\|');

/** Map of absolute path -> content for every generated file. */
function render() {
  const out = new Map();
  for (const [letter, folder] of Object.entries(AREAS)) {
    const pbs = playbooks.filter((p) => p.area === letter);
    const lines = [
      `# Area ${letter}: ${folder}`, '',
      'Generated by `tools/generate.mjs` from `registry/playbooks.tsv` and `registry/units.tsv`. Do not edit.', '',
      '| id | name | status | units | playbook | rubric |', '| --- | --- | --- | --: | --- | --- |',
      ...pbs.map((p) => `| ${p.id} | ${cell(p.name)} | ${p.status} | ${owned(p.id).length} | ${playbookLink(folder, p.id)} | [rubric](../../rubrics/${p.id}.md) |`),
    ];
    for (const p of pbs) {
      lines.push('', `## ${p.id} ${p.name}`, '', '| unit | book | name | kind |', '| --- | --- | --- | --- |');
      for (const u of owned(p.id)) lines.push(`| ${u.unit_id} | ${u.book} | ${cell(u.unit)} | ${u.kind} |`);
    }
    out.set(path.join(skill, 'playbooks', folder, 'INDEX.md'), lines.join('\n') + '\n');
  }
  for (const p of playbooks.filter(isDomain)) {
    const rules = conflicts.filter((k) => k.approved === 'yes' && k.rule.trim()
      && (k.playbook === p.id || (p.id === 'H11' && k.id === 'K12')));
    const lines = [
      `Generated by \`tools/generate.mjs\` from the criteria of the units ${p.id} owns in \`registry/units.tsv\` and \`registry/units/<book>.md\`. Do not edit.`, '',
      `# Rubric ${p.id}: ${p.name}`,
    ];
    if (rules.length) {
      lines.push('', '## Spareggi approvati', '',
        'Applica gli spareggi pertinenti alla variante. Se un criterio di fonte li contraddice, segnalo come non applicabile e valuta la regola approvata.');
      for (const k of rules) lines.push(`- ${k.id}: ${k.rule}`);
    }
    for (const u of owned(p.id)) {
      lines.push('', `## ${u.unit_id} ${u.unit} (${u.book})`, '');
      const sec = sections.get(u.unit_id);
      if (!sec) { lines.push('- (no section in registry/units)'); continue; }
      const k02 = u.unit_id === 'E-037' && rules.some((k) => k.id === 'K02');
      for (const c of sec.criteria) {
        if (k02 && ['Uses the five scripted questions.', 'Reports yes count against majority.'].includes(c.text)) continue;
        lines.push(`- ${c.text}${c.cites.length ? ` [${c.cites.join(', ')}]` : ''}`);
      }
      if (k02) {
        lines.push('- K02 (A-031, A-033): lo script indaga episodi passati o comportamenti attuali. Una domanda ipotetica di acquisto o raccomandazione viola il criterio.',
          '- K02 (A-033, E-037): confronta gli impegni concreti ottenuti con la maggioranza degli intervistati. Conta al massimo un impegno per persona ed escludi intenzioni e complimenti.');
      }
    }
    out.set(path.join(skill, 'rubrics', `${p.id}.md`), lines.join('\n') + '\n');
  }
  const books = [...new Set(units.map((u) => u.book))].sort();
  const lib = [
    '# Library', '',
    'Generated by `tools/generate.mjs` from `registry/units.tsv`. Do not edit.', '',
    '| book | units | owners |', '| --- | --: | --- |',
    ...books.map((b) => {
      const us = units.filter((u) => u.book === b);
      const owners = playbooks.map((p) => p.id).filter((id) => us.some((u) => u.owner === id));
      return `| ${b} | ${us.length} | ${owners.join(', ')} |`;
    }),
  ];
  out.set(path.join(skill, 'references', 'library.md'), lib.join('\n') + '\n');
  return out;
}
const expected = render();
// A written playbook is <id>-<slug>.md in its area folder; until it exists the index says so.
function playbookLink(folder, id) {
  const dir = path.join(skill, 'playbooks', folder);
  const file = fs.existsSync(dir) ? fs.readdirSync(dir).find((f) => f.startsWith(`${id}-`) && f.endsWith('.md')) : undefined;
  return file ? `[${file}](${file})` : 'not written';
}

// The rubrics folder is wholly generated: a file the registry no longer produces is stale.
const rubricsDir = path.join(skill, 'rubrics');
const stale = fs.existsSync(rubricsDir)
  ? fs.readdirSync(rubricsDir).map((f) => path.join(rubricsDir, f)).filter((f) => !expected.has(f))
  : [];

if (opts.check) {
  const bad = [...expected].filter(([f, text]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== text).map(([f]) => f);
  for (const f of bad) console.log(`out of date: ${path.relative(opts.root, f)}`);
  for (const f of stale) console.log(`stale: ${path.relative(opts.root, f)}`);
  console.log(`generate --check: ${expected.size} files, ${bad.length + stale.length} differ`);
  process.exit(bad.length + stale.length ? 1 : 0);
}
for (const f of stale) fs.rmSync(f);
for (const [f, text] of expected) {
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, text);
}
console.log(`generate: wrote ${expected.size} files${stale.length ? `, removed ${stale.length} stale` : ''}`);
